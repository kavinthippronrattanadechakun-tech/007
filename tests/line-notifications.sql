begin;
do $$
declare u uuid;a uuid;p text:='line-'||gen_random_uuid();o uuid;auto_o uuid;done_o uuid;j jsonb;j2 jsonb;lease uuid;job uuid;dest text:='C'||repeat('a',32);
begin
 select id into a from public.profiles where is_admin limit 1;
 select id into u from public.profiles limit 1;
 insert into public.products(id,title,price,active,delivery_type,duration_days) values(p,'LINE manual fixture',1,true,'manual',7),(p||'-auto','Automatic fixture',1,true,'code',1);
 insert into public.orders(user_id,product_id,price,status,customer_email) values(u,p,1,'processing','receiver@example.com') returning id into o;
 insert into public.orders(user_id,product_id,price,status) values(u,p||'-auto',1,'delivered') returning id into auto_o;
 if not exists(select 1 from public.line_order_notifications where order_id=o) then raise exception 'manual order not queued';end if;
 if exists(select 1 from public.line_order_notifications where order_id=auto_o) then raise exception 'automatic order queued';end if;
 if public.claim_line_order_notification(o) is not null then raise exception 'disabled config dispatched';end if;
 insert into public.line_destinations(id,kind) values(dest,'group') on conflict(id) do nothing;
 update public.line_settings set enabled=true,target_id=dest where id=true;
 j:=public.claim_line_order_notification(o);job:=(j->>'id')::uuid;lease:=(j->>'lease_token')::uuid;
 if j is null or j->>'to'<>dest or position('receiver@example.com' in (j->>'text'))=0 then raise exception 'wrong payload';end if;
 if public.claim_line_order_notification(o) is not null then raise exception 'active lease claimed twice';end if;
 if public.finish_line_order_notification(job,gen_random_uuid(),true,null,true) then raise exception 'wrong lease completed';end if;
 perform public.finish_line_order_notification(job,lease,false,'network_error',true);
 if public.claim_line_order_notification(o) is not null then raise exception 'retry delay ignored';end if;
 update public.line_order_notifications set next_attempt_at=now()-interval '1 second' where id=job;
 j2:=public.claim_line_order_notification(o);
 if j2->>'retry_key'<>j->>'retry_key' or j2->>'text'<>j->>'text' or j2->>'to'<>j->>'to' then raise exception 'retry payload changed';end if;
 perform public.finish_line_order_notification(job,(j2->>'lease_token')::uuid,true,null,true);
 if public.claim_line_order_notification(o) is not null then raise exception 'sent job dispatched again';end if;
 perform public.retry_line_order_notifications(a);
 if (select status from public.line_order_notifications where id=job)<>'sent' then raise exception 'admin retry reset sent job';end if;
 insert into public.orders(user_id,product_id,price,status) values(u,p,1,'processing') returning id into done_o;
 perform public.admin_fulfill_order(done_o,a,E'Mail: sent@example.com\nPassword: secret');
 if public.claim_line_order_notification(done_o) is not null then raise exception 'fulfilled order notified';end if;
 if (select status from public.line_order_notifications where order_id=done_o)<>'skipped' then raise exception 'fulfilled job not skipped';end if;
 insert into public.orders(user_id,product_id,price,status) values(u,p,1,'processing') returning id into done_o;
 update public.line_order_notifications set first_attempt_at=now()-interval '25 hours',attempts=1,target_id=dest where order_id=done_o;
 if public.claim_line_order_notification(done_o) is not null then raise exception 'expired retry auto sent';end if;
 if (select status from public.line_order_notifications where order_id=done_o)<>'failed' then raise exception 'expired retry not failed';end if;
 select retry_key into lease from public.line_order_notifications where order_id=done_o;
 perform public.retry_line_order_notifications(a);
 if (select retry_key from public.line_order_notifications where order_id=done_o)=lease then raise exception 'explicit late retry reused expired key';end if;
 if has_table_privilege('authenticated','public.line_destinations','select') or has_table_privilege('anon','public.line_settings','select') or has_table_privilege('authenticated','public.line_order_notifications','select') then raise exception 'LINE data exposed';end if;
 if has_function_privilege('authenticated','public.claim_line_order_notification(uuid)','execute') or has_function_privilege('anon','public.retry_line_order_notifications(uuid)','execute') then raise exception 'LINE RPC exposed';end if;
 perform set_config('test.line_order',done_o::text,true);
 update public.profiles set balance=balance+1 where id=u;
 perform set_config('request.jwt.claims',jsonb_build_object('sub',u::text,'role','authenticated')::text,true);
 perform set_config('test.line_product',p,true);
end$$;
set local role authenticated;
with purchased as (select public.buy_product(current_setting('test.line_product')) as result)
select result->>'status'='processing' as authenticated_purchase_works,set_config('test.purchase_order',result->>'order_id',true) is not null as order_captured from purchased;
reset role;
select exists(select 1 from public.line_order_notifications where order_id=current_setting('test.purchase_order')::uuid) as authenticated_purchase_queued;
set local role service_role;
select public.claim_line_order_notification(current_setting('test.line_order')::uuid) is not null as service_role_claim_works;
rollback;
